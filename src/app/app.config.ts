// `?v=${BUILD_STAMP}` makes every build request a new URL for /i18n/*.json,
// so returning visitors bypass whatever a browser heuristically cached for
// the old URL. Production nginx sends no Cache-Control for /i18n/ (a
// separate fix), which otherwise lets browsers reuse stale translations for
// days after a deploy. BUILD_STAMP comes from build-info.ts, regenerated by
// scripts/generate-build-info.js on every `npm run build`/`npm test`.
export const translateHttpLoaderProviders = provideTranslateHttpLoader({
  prefix: '/i18n/',
  suffix: `.json?v=${BUILD_STAMP}`,
});

/**
 * "Refined Warm" (Direction A) preset over Aura. Maps PrimeNG's `primary`
 * ramp + light color-scheme to the DoRent warm-orange tokens so components
 * we don't hand-style (datepicker focus/range, checkboxes, focus rings, etc.)
 * inherit the brand palette instead of Aura's default emerald/indigo.
 * Hex values mirror src/styles.css design tokens (prototype system.jsx TOKENS.A).
 */
const DoRentPreset = definePreset(Aura, {
  semantic: {
    primary: {
      50: '#fff4ec',
      100: '#ffeedc',
      200: '#ffd9b8',
      300: '#ffbd8a',
      400: '#ff8f47',
      500: '#ff6008',
      600: '#e5530a',
      700: '#c2440a',
      800: '#9c360a',
      900: '#7e2f0c',
      950: '#451705',
    },
    focusRing: {
      width: '3px',
      style: 'solid',
      // ADR-031: a focus ring is non-text and needs 3:1 on the #faf8f4 page; #ff6008 measures 2.86.
      color: '#c24600',
      offset: '2px',
    },
    colorScheme: {
      light: {
        primary: {
          color: '#ff6008',
          contrastColor: '#ffffff',
          hoverColor: '#e5530a',
          activeColor: '#c2440a',
        },
        highlight: {
          background: '#ffeedc',
          focusBackground: '#ffd9b8',
          color: '#9c360a',
          focusColor: '#7e2f0c',
        },
        content: {
          borderColor: '#e8e5de',
        },
        formField: {
          borderColor: '#e8e5de',
          focusBorderColor: '#c24600',
        },
      },
    },
  },
  // ADR-031 (amended 2026-10-13): white text on orange, and orange text, use the strong shade
  // (#c24600 / hover #a83c00 / active #943300). primary.500 and `primary.color` stay #ff6008 so
  // non-text uses (checkbox/radio fills, slider, progress) keep the brand orange.
  components: {
    button: {
      colorScheme: {
        light: {
          root: {
            primary: {
              background: '#c24600',
              hoverBackground: '#a83c00',
              activeBackground: '#943300',
              borderColor: '#c24600',
              hoverBorderColor: '#a83c00',
              activeBorderColor: '#943300',
              focusRing: { color: '#c24600', shadow: 'none' },
            },
          },
          outlined: { primary: { color: '#c24600' } },
          text: { primary: { color: '#c24600' } },
          link: { color: '#c24600', hoverColor: '#a83c00', activeColor: '#943300' },
        },
      },
    },
    // Selected day: white text on the fill.
    datepicker: {
      date: { selectedBackground: '#c24600' },
    },
  },
});

export const appConfig: ApplicationConfig = {
  providers: [
    provideBrowserGlobalErrorListeners(),
    // DoRent is single-currency (AMD) app-wide — no per-listing currency code,
    // no user-selectable display currency (yet). Registering the default here
    // means anything that ever falls back to Angular's bare `currency` pipe
    // resolves to AMD instead of the framework default (USD). Actual price
    // rendering across the app goes through `shared/utils/dram-currency.pipe`
    // instead, because Angular's bundled locale data has no ֏ symbol entry
    // for AMD (see that pipe's doc comment) — this provider is the registration
    // + safety net, not the formatting mechanism.
    { provide: DEFAULT_CURRENCY_CODE, useValue: 'AMD' },
    // `TILE_PROVIDER_CONFIG` (shared/ui/map/map.component.ts) already defaults
    // to `environment.tileProvider` via its own `providedIn: 'root'` factory —
    // this explicit entry exists for discoverability (app-level config lives
    // here, alongside DEFAULT_CURRENCY_CODE above) rather than to change the
    // resolved value.
    { provide: TILE_PROVIDER_CONFIG, useValue: environment.tileProvider },
    provideRouter(routes),
    provideHttpClient(withInterceptors([authInterceptor])),
    provideStore({}, { metaReducers: sessionResetMetaReducers }),
    // Auth is the only eagerly-registered slice: the app shell reads auth
    // state and dispatches authInitStarted at bootstrap. Every other feature
    // slice is registered lazily on the route(s) that consume it (see each
    // feature's routes.ts).
    provideState(authFeatureKey, authReducer),
    provideEffects(AuthEffects),
    translateHttpLoaderProviders[0],
    ...provideTranslateService({
      fallbackLang: 'en',
      lang: 'en',
      loader: translateHttpLoaderProviders[1],
    }),
    providePrimeNG({
      // DatePicker's month/year buttons show the current month/year as text but carry a static
      // aria-label ("Choose Month"/"Choose Year") that does not contain it (axe
      // label-content-name-mismatch). Empty labels let the buttons take their accessible name
      // from the visible text (ADR-033). The month/day names follow the UI language:
      // LanguageService pushes them via PrimeNG.setTranslation (and keeps these two empty).
      // PrimeNG merges this over its default translation, so only these two keys change.
      translation: { chooseMonth: '', chooseYear: '' },
      theme: {
        preset: DoRentPreset,
        options: {
          darkModeSelector: false,
        },
      },
    }),
    MessageService,
  ],
};
